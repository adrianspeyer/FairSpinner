'use strict';

// Rebuild the checked-in, browser-ready verifier from exact package-lock pins.
// npm ci --ignore-scripts && npm run build:beacon
// --check compares deterministic output without changing files.
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.join(__dirname, '..');
const target = path.join(root, 'vendor', 'beacon-verifier.js');
for (const [name, expected] of [['@noble/curves', '2.4.0'], ['@noble/hashes', '2.4.0'], ['esbuild', '0.28.2']]) {
  const installed = JSON.parse(fs.readFileSync(path.join(root, 'node_modules', name, 'package.json'), 'utf8')).version;
  if (installed !== expected) throw new Error(`${name} must be ${expected}; update the reviewed pins and notices explicitly.`);
}
const license = fs.readFileSync(path.join(root, 'node_modules', '@noble', 'curves', 'LICENSE'), 'utf8').trim();
const hashLicense = fs.readFileSync(path.join(root, 'node_modules', '@noble', 'hashes', 'LICENSE'), 'utf8').trim();
if (license !== hashLicense) throw new Error('Noble license texts differ; update bundled notices explicitly.');
const banner = `/*!
FairSpin drand quicknet verifier. Generated by scripts/build-beacon.cjs.
Wrapper: PolyForm-Noncommercial-1.0.0; https://polyformproject.org/licenses/noncommercial/1.0.0
Required Notice: Copyright (c) 2026 Adrian Speyer (https://github.com/adrianspeyer/FairSpinner)
Bundled @noble/curves 2.4.0 and @noble/hashes 2.4.0 retain the following MIT license:

${license}
*/`;
const result = esbuild.buildSync({
  absWorkingDir: root,
  entryPoints: ['crypto/beacon-verifier.js'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  charset: 'ascii',
  banner: { js: banner },
  write: false,
  logLevel: 'silent',
});
const output = result.outputFiles[0].text;
if (/<\/script/i.test(output)) throw new Error('Bundle contains a closing script tag; cannot safely embed.');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('Beacon bundle is stale. Run npm run build:beacon.'); process.exitCode = 1;
  } else console.log('Beacon bundle matches its source and pinned dependencies.');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  console.log(`Built vendor/beacon-verifier.js (${Buffer.byteLength(output)} bytes).`);
}
